/** Brand colors that have no Material 3 role. */
@Immutable
data class PopReelExtendedColors(
    val brandStart: Color,
    val brandEnd: Color,
    val positive: Color,
)

private val DarkExtendedColors = PopReelExtendedColors(BrandAmber, BrandCoral, PositiveDark)
private val LightExtendedColors = PopReelExtendedColors(BrandAmber, BrandCoral, PositiveLight)

val LocalPopReelExtendedColors = staticCompositionLocalOf { DarkExtendedColors }

/**
 * PopReel Material 3 theme. Dynamic color is intentionally not used, so the
 * Stitch brand palette is applied on every device.
 */
@Composable
fun PopReelTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val extended = if (darkTheme) DarkExtendedColors else LightExtendedColors

    CompositionLocalProvider(
        LocalPopReelExtendedColors provides extended,
        LocalPopReelSpacing provides PopReelSpacing(),
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content,
        )
    }
}

/** Accessors for PopReel-specific tokens, mirroring `MaterialTheme.*`. */
object PopReelTheme {
    val extendedColors: PopReelExtendedColors
        @Composable @ReadOnlyComposable get() = LocalPopReelExtendedColors.current

    val spacing: PopReelSpacing
        @Composable @ReadOnlyComposable get() = LocalPopReelSpacing.current
}
